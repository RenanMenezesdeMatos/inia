import { createRequire } from "node:module"
const { webkit } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_CORE)
const [model, fixtureLabel] = process.argv.slice(2)
const browser = await webkit.launch()
const page = await browser.newPage({ viewport: { width: 1500, height: 1000 }, deviceScaleFactor: 1 })
page.on("pageerror", (e) => console.log("PAGEERROR", e.message))
await page.goto(`http://localhost:3000/dev/avatar-lab?model=${model}&view=chat&upload=http://127.0.0.1:8765/${model}.webm`, { waitUntil: "load" })
await page.waitForSelector("canvas")
await page.waitForFunction(() => !document.body.innerText.includes("Carregando avatar"), null, { timeout: 60000 })
await page.waitForTimeout(2500)
await page.getByLabel("Captura (resposta da INIA)").selectOption({ label: fixtureLabel })
await page.getByRole("button", { name: "Gravar demonstração" }).click()
await page.waitForTimeout(9000)
await page.getByRole("button", { name: "Ouvindo", exact: true }).click()
await page.waitForTimeout(6000)
await page.getByRole("button", { name: /^Enviar fala simulada|^Play$/ }).click()   // fala
const t0 = Date.now()
await page.waitForFunction(() => /estado: speaking/.test(document.querySelector('header')?.innerText ?? ''), null, { timeout: 20000 }).catch(() => console.log("não começou a falar"))
await page.waitForFunction(() => !/estado: speaking/.test(document.querySelector('header')?.innerText ?? ''), null, { timeout: 90000 }).catch(() => console.log("timeout esperando fim da fala"))
console.log("fala (s)", (Date.now() - t0) / 1000)
await page.waitForTimeout(1500)
await page.getByRole("button", { name: "Parar gravação" }).click()
await page.waitForFunction(() => { const m = document.body.innerText.match(/Upload: ([^\n]*)/); return !!m && !m[1].includes('enviando') }, null, { timeout: 60000 }).catch(() => console.log("sem confirmação de upload"))
const diag = await page.evaluate(() => document.body.innerText.split("\n").filter((l) => /^Upload:/i.test(l)).join(" | "))
console.log(model, diag.slice(0, 500))
await browser.close()
